"""NRLMSISE-00 empirical spherical harmonics with per-evaluation state.

The published model defines its coefficient indices and rounded angular
constants. Legendre functions are generated by recurrence. No reference code,
parameter tables or mutable global model state are imported.
"""

from __future__ import annotations

from math import cos, exp, expm1, sin


class MSISHarmonics:
    def __init__(
        self,
        latitude: float,
        longitude: float,
        day: int,
        seconds: float,
        solar_flux: float,
        mean_solar_flux: float,
        daily_ap: float,
        ap_history: tuple[float, ...] | None,
    ) -> None:
        self.latitude, self.longitude, self.day, self.seconds = latitude, longitude, day, seconds
        self.flux_delta, self.mean_delta = solar_flux - mean_solar_flux, mean_solar_flux - 150
        self.daily_ap, self.history = daily_ap, ap_history
        self.hour_angle = 0.2618 * (seconds / 3600 + longitude / 15)
        self.last_ap = 0.0
        self.legendre = [[0.0] * 8 for _ in range(4)]
        x, y = sin(latitude * 0.0174533), cos(latitude * 0.0174533)
        self.legendre[0][0] = 1.0
        for m in range(4):
            if m:
                self.legendre[m][m] = (2 * m - 1) * y * self.legendre[m - 1][m - 1]
            for n in range(m + 1, 8):
                self.legendre[m][n] = (
                    (2 * n - 1) * x * self.legendre[m][n - 1]
                    - (n + m - 1) * (self.legendre[m][n - 2] if n > m + 1 else 0)
                ) / (n - m)

    def _daily_response(self, rate: float, slope: float) -> float:
        rate = 1e-5 if rate < 0 else rate
        if rate == 0:
            return 0.0
        offset = self.daily_ap - 4
        return offset + (slope - 1) * (offset + expm1(-rate * offset) / rate)

    def _historical_response(self, p: tuple[float, ...]) -> float:
        assert self.history is not None
        decay = min(0.99999, exp(-10800 * abs(p[51]) / (1 + p[138] * (45 - abs(self.latitude)))))
        rate = max(abs(p[24]), 0.0001)
        values = [
            a - 4 + (p[25] - 1) * (a - 4 + expm1(-rate * (a - 4)) / rate) for a in self.history[1:]
        ]
        tail = sum(decay**k for k in range(8))
        numerator = sum(values[k] * decay**k for k in range(4))
        numerator += tail * (values[4] * decay**4 + values[5] * decay**12)
        return numerator / (1 + decay**0.5 * sum(decay**k for k in range(19)))

    def evaluate(self, p: tuple[float, ...], *, lower: bool = False) -> float:
        """All standard model switches on; optional seven-index AP history."""
        leg = self.legendre
        df, da = self.flux_delta, self.mean_delta
        annual = cos(0.0172142 * (self.day - p[13]))
        sym_annual = cos(0.0172142 * (self.day - p[31]))
        semi = cos(2 * 0.0172142 * (self.day - p[17]))
        asym_semi = cos(2 * 0.0172142 * (self.day - p[38]))

        def dot(order: int, degrees: tuple[int, ...], indices: tuple[int, ...]) -> float:
            return sum(
                leg[order][degree] * p[index]
                for degree, index in zip(degrees, indices, strict=True)
            )

        odd, even = (1, 3, 5), (2, 4, 6)
        terms = [0.0] * 14
        f1 = 1 + p[47] * da + p[19] * df + p[20] * df**2
        f2 = 1 + p[49] * da + p[19] * df + p[20] * df**2
        if lower:
            f1 = f2 = 1.0
            terms[0] = p[21] * da
            terms[1] = dot(0, even, (1, 2, 22)) + dot(0, odd, (26, 14, 59))
            terms[2] = (p[18] + dot(0, (2, 4), (47, 29))) * sym_annual
            terms[3] = (p[15] + dot(0, (2, 4), (16, 30))) * semi
            terms[4] = dot(0, odd, (9, 10, 20)) * annual
        else:
            terms[0] = p[19] * df * (1 + p[59] * da) + p[20] * df**2 + p[21] * da + p[29] * da**2
            terms[1] = dot(0, even, (1, 2, 22)) + p[14] * leg[0][2] * da + p[26] * leg[0][1]
            terms[2] = p[18] * sym_annual
            terms[3] = (p[15] + p[16] * leg[0][2]) * semi
            terms[4] = f1 * dot(0, (1, 3), (9, 10)) * annual
        terms[5] = p[37] * leg[0][1] * asym_semi
        degrees = (1, 3) if lower else odd
        cos_indices, sin_indices = ((3, 4), (6, 7)) if lower else ((3, 4, 27), (6, 7, 28))
        terms[6] = f2 * (
            (dot(1, degrees, cos_indices) + p[11] * leg[1][2] * annual) * cos(self.hour_angle)
            + (dot(1, degrees, sin_indices) + p[12] * leg[1][2] * annual) * sin(self.hour_angle)
        )
        terms[7] = f2 * (
            (dot(2, (2, 4), (5, 41)) + dot(2, (3, 5), (23, 35)) * annual) * cos(2 * self.hour_angle)
            + (dot(2, (2, 4), (8, 42)) + dot(2, (3, 5), (33, 36)) * annual)
            * sin(2 * self.hour_angle)
        )
        terms[13] = f2 * (
            (p[39] * leg[3][3] + (0 if lower else dot(3, (4, 6), (93, 46)) * annual))
            * sin(3 * self.hour_angle)
            + (p[40] * leg[3][3] + (0 if lower else dot(3, (4, 6), (94, 48)) * annual))
            * cos(3 * self.hour_angle)
        )
        if self.history is None:
            magnetic = self._daily_response(p[43], p[44])
        else:
            if not lower and p[51] != 0:
                self.last_ap = self._historical_response(p)
            magnetic = self.last_ap
        if lower:
            terms[8] = (
                magnetic * (p[32] + p[45] * leg[0][2])
                if self.history is None
                else (magnetic * (p[50] + p[96] * leg[0][2]))
            )
        else:
            indices: tuple[int, ...] = (32, 45, 34, 100, 101, 102, 121, 122, 123, 124)
            if self.history is not None:
                indices = (50, 96, 54, 125, 126, 127, 128, 129, 130, 131)
            terms[8] = magnetic * (
                p[indices[0]]
                + dot(0, (2, 4), indices[1:3])
                + dot(0, odd, indices[3:6]) * annual
                + dot(1, odd, indices[6:9]) * cos(self.hour_angle - 0.2618 * p[indices[9]])
            )
            if self.history is not None and p[51] == 0:
                terms[8] = 0.0
        lon = 0.0174533 * self.longitude
        if lower:
            seasonal = 1 + leg[0][1] * (
                p[80] * cos(0.0172142 * (self.day - p[81]))
                + p[85] * cos(2 * 0.0172142 * (self.day - p[86]))
            )
            seasonal += p[83] * cos(0.0172142 * (self.day - p[84]))
            seasonal += p[87] * cos(2 * 0.0172142 * (self.day - p[88]))
            terms[10] = seasonal * (
                (dot(1, even, (64, 65, 66)) + dot(1, odd, (74, 75, 76))) * cos(lon)
                + (dot(1, even, (90, 91, 92)) + dot(1, odd, (77, 78, 79))) * sin(lon)
            )
        else:
            terms[10] = (1 + p[80] * da) * (
                (
                    dot(1, even, (64, 65, 66))
                    + dot(1, odd, (103, 104, 105))
                    + dot(1, odd, (109, 110, 111)) * annual
                )
                * cos(lon)
                + (
                    dot(1, even, (90, 91, 92))
                    + dot(1, odd, (106, 107, 108))
                    + dot(1, odd, (112, 113, 114)) * annual
                )
                * sin(lon)
            )
            terms[11] = (
                (1 + p[95] * leg[0][1]) * (1 + p[81] * da) * (1 + p[119] * leg[0][1] * annual)
            )
            terms[11] *= dot(0, odd, (68, 69, 70)) * cos(0.000072722 * (self.seconds - p[71]))
            terms[11] += (
                dot(2, (3, 5, 7), (76, 77, 78))
                * (1 + p[137] * da)
                * cos(0.000072722 * (self.seconds - p[79]) + 2 * lon)
            )
            indices = (120, 60, 61, 62, 63, 115, 116, 117, 118, 83, 84, 85, 75)
            if self.history is not None:
                indices = (132, 52, 98, 67, 97, 133, 134, 135, 136, 55, 56, 57, 58)
            terms[12] = magnetic * (
                (1 + p[indices[0]] * leg[0][1])
                * dot(1, even, indices[1:4])
                * cos(lon - 0.0174533 * p[indices[4]])
                + dot(1, odd, indices[5:8]) * annual * cos(lon - 0.0174533 * p[indices[8]])
                + dot(0, odd, indices[9:12]) * cos(0.000072722 * (self.seconds - p[indices[12]]))
            )
            if self.history is not None and p[51] == 0:
                terms[12] = 0.0
        return sum(terms) + (0 if lower else p[30])
