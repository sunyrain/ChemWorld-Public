/* Inline API documentation. All code, signatures and outputs are built from the public package. */
(() => {
  'use strict';
  const esc = value => String(value ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const json = value => JSON.stringify(value, null, 2);
  const text = {
    zh: {
      interface:'调用接口', parameters:'参数与返回', parameter:'参数', type:'类型', default:'默认值 / 必填',
      required:'必填', untyped:'未注解', returns:'返回类型', native:'接口说明', input:'示例输入', code:'完整调用代码',
      output:'实际输出', copy:'复制', copied:'已复制', copyFailed:'请选中文本复制', example:'示例', more:'更多示例',
      verified:'下列输出由展示的代码实际运行生成。数值末位可能随平台或求解库版本变化。',
      shared:'本方法与父能力共用下面的示例；示例演示的具体范围见说明。',
      planned:'尚未提供调用接口', plannedNote:'这是规划能力，目前没有已实现的 API、可运行示例或实测输出。',
      missing:'此条目的接口文档尚未加载，请刷新后重试。',
      schema:'动作字段', schemaNote:'以下合同来自示例会话初始化后的 action_schema()。单位、枚举和范围取决于装置、任务及当前状态；执行前可用 validate_action() 再检查。',
      field:'字段', unit:'单位', bounds:'范围 / 选项', details:'完整动作合同', optional:'可选',
      checks:'示例验证', checksNote:'这些是固定合成输入的软件使用示例，用于核对接口、代码与输出。它们不扩大材料验证、科学资格或正式评测的范围。',
      long:'可滚动查看并复制完整内容', alternatives:'本例涉及的其他接口',
    },
    en: {
      interface:'API', parameters:'Parameters & return', parameter:'Parameter', type:'Type', default:'Default / required',
      required:'Required', untyped:'Unannotated', returns:'Return annotation', native:'API description', input:'Example input', code:'Complete Python example',
      output:'Actual output', copy:'Copy', copied:'Copied', copyFailed:'Select text to copy', example:'Example', more:'More examples',
      verified:'Outputs below were generated by executing the displayed code. Last digits may vary with platform or solver versions.',
      shared:'This method shares the example below with its parent capability. Its demonstrated scope is stated explicitly.',
      planned:'No callable API yet', plannedNote:'This is a planned capability. No implemented API, runnable example or executed output is available yet.',
      missing:'The API reference for this item did not load. Refresh to try again.',
      schema:'Action fields', schemaNote:'These contracts come from action_schema() after initializing the example session. Units, choices and bounds depend on apparatus, task and state; use validate_action() before execution.',
      field:'Field', unit:'Unit', bounds:'Bounds / choices', details:'Full action contract', optional:'Optional',
      checks:'Example verification', checksNote:'These fixed synthetic software examples check agreement between interface, code and output. They do not extend material validation, scientific qualification or benchmark claims.',
      long:'Scroll to read or copy the full content', alternatives:'Other interfaces used in this example',
    }
  };
  function codeBlock(value, label, t, kind) {
    const content = typeof value === 'string' ? value : json(value);
    return `<div class="api-code" data-api-block="${kind}"><div class="api-code-bar"><span>${esc(label)}</span><button type="button" data-api-copy data-copy-label="${esc(t.copy)}" data-copied-label="${esc(t.copied)}" data-error-label="${esc(t.copyFailed)}" aria-label="${esc(t.copy+' '+label)}">${esc(t.copy)}</button><span class="api-copy-status" role="status"></span></div><pre tabindex="0" aria-label="${esc(label)}"><code>${esc(content)}</code></pre>${content.split('\n').length>24?`<div class="api-scroll-note">${esc(t.long)}</div>`:''}</div>`;
  }
  function parameterTable(api,t) {
    const rows = api.parameters.map(p=>`<tr><th scope="row"><code>${esc(p.name)}</code>${p.kind==='KEYWORD_ONLY'?'<small>keyword-only</small>':''}</th><td><code>${esc(p.type||t.untyped)}</code></td><td><code>${esc(p.required?t.required:p.default||'—')}</code></td></tr>`).join('');
    return `${rows?`<div class="api-table-scroll" tabindex="0"><table class="api-parameters"><thead><tr><th scope="col">${t.parameter}</th><th scope="col">${t.type}</th><th scope="col">${t.default}</th></tr></thead><tbody>${rows}</tbody></table></div>`:''}<p class="api-return">${t.returns}: <code>${esc(api.returns||t.untyped)}</code></p>${api.doc&&!api.doc.startsWith(api.signature.split('(')[0]+'(')?`<details class="api-native-doc"><summary>${t.native}</summary><p>${esc(api.doc)}</p></details>`:''}`;
  }
  function interfaceBlock(api,t,expanded) {
    return `<div class="api-interface"><p class="api-import"><code>${esc(api.path)}</code></p>${codeBlock(api.signature,t.interface,t,'signature')}<details class="api-parameter-details"${expanded?' open':''}><summary>${t.parameters}</summary>${parameterTable(api,t)}</details></div>`;
  }
  function actionFields(recipe,t) {
    const output=recipe.output;
    const schemas=output?.action_schemas || (output?.action_schema?{[output.action_schema.operation]:output.action_schema}:{});
    if(!Object.keys(schemas).length)return '';
    return `<h3>${t.schema}</h3><p>${t.schemaNote}</p>${Object.entries(schemas).map(([name,schema])=>`<details class="api-action"><summary><code>${esc(name)}</code> · ${schema.fields?.length||0} ${t.field}</summary><div class="api-table-scroll" tabindex="0"><table class="api-parameters"><thead><tr><th>${t.field}</th><th>${t.type}</th><th>${t.unit}</th><th>${t.bounds}</th></tr></thead><tbody>${(schema.fields||[]).map(f=>`<tr><th scope="row"><code>${esc(f.field)}</code><small>${f.required?t.required:t.optional}</small></th><td>${esc(f.type||'—')}</td><td>${esc(f.unit||'—')}</td><td><code>${esc(json(f.bounds||f.choices||f.enum||f.options||null)||'—')}</code></td></tr>`).join('')}</tbody></table></div>${codeBlock(schema,t.details,t,'schema')}</details>`).join('')}`;
  }
  function recipeContent(recipe,t,lang,mode) {
    const interfaces=recipe.apis;
    let html=`<p class="api-example-note">${esc(recipe.notes[lang])}</p>`;
    if(mode!=='examples') {
      html+=interfaceBlock(interfaces[0],t,mode==='io');
      if(interfaces.length>1)html+=`<details class="api-other-interfaces"><summary>${t.alternatives} (${interfaces.length-1})</summary>${interfaces.slice(1).map(a=>interfaceBlock(a,t,mode==='io')).join('')}</details>`;
      html+=actionFields(recipe,t);
    }
    html+=`<h3>${t.input}</h3>${codeBlock(recipe.inputs,'JSON',t,'input')}`;
    if(mode!=='io')html+=`<h3>${t.code}</h3>${codeBlock(recipe.code,'Python',t,'python')}`;
    html+=`<h3>${t.output}</h3>${codeBlock(recipe.output,'JSON',t,'output')}`;
    return html;
  }
  function render(node,lang='zh',mode='overview') {
    if(!['capability','method'].includes(node.kind))return null;
    const t=text[lang]||text.en, data=window.CHEMWORLD_API_REFERENCE, entry=data?.nodes[node.id];
    if(node.state==='planned')return `<div class="api-planned"><h2>${t.planned}</h2><p>${t.plannedNote}</p><p>${esc(node.boundary)}</p></div>`;
    if(!entry?.examples?.length)return `<p class="api-missing" role="alert">${t.missing}</p>`;
    if(mode==='validation')return `<div class="api-verification"><h2>${t.checks}</h2><p>${t.verified}</p><p>${esc(data.coverage.execution)} · ${entry.examples.length} ${t.example}</p><p>${t.checksNote}</p></div>`;
    const examples=entry.examples.map(key=>({key,...data.recipes[key]}));
    return `<section class="api-reference" data-api-node="${esc(node.id)}">${entry.shared_example?`<p class="scope-statement">${t.shared}</p>`:''}${examples.map((recipe,index)=>{
      const label=`${t.example} ${index+1} · ${recipe.apis[0].path.split('.').slice(-1)[0]}`;
      const body=recipeContent(recipe,t,lang,mode);
      return index===0?`<article class="api-example" data-api-recipe="${recipe.key}"><h2>${esc(label)}</h2>${body}</article>`:`<details class="api-example api-example-more" data-api-recipe="${recipe.key}"><summary>${esc(label)}</summary>${body}</details>`;
    }).join('')}</section>`;
  }
  document.addEventListener('click',async event=>{
    const button=event.target.closest('[data-api-copy]');if(!button)return;
    const code=button.closest('.api-code').querySelector('code').textContent;
    const status=button.parentElement.querySelector('.api-copy-status');
    try {await navigator.clipboard.writeText(code);status.textContent=button.dataset.copiedLabel;}
    catch {status.textContent=button.dataset.errorLabel;}
    setTimeout(()=>{status.textContent='';},2500);
  });
  window.ChemWorldApiDocs={render};
})();
